    '/(?<=[A-Za-z])-ის(?![\\x{10A0}-\\x{10FF}])/u' => '',
];

function translate(string $name, array $map, array $units, int $li): string
{
    $out = ' '.trim($name).' ';
    foreach ($map as $ka => $t) {
        if (mb_strpos($out, $ka) === false) {
            continue;
        }
        // only replace when not glued to another Georgian letter (avoids
        // matching a phrase inside a longer inflected Georgian word)
        $re = '/(?<![\x{10A0}-\x{10FF}])'.preg_quote($ka, '/').'(?![\x{10A0}-\x{10FF}])/u';
        $out = preg_replace($re, $t[$li], $out) ?? $out;
    }
    foreach ($units as $re => $rep) {
        $out = preg_replace($re, $rep, $out);
    }
    $out = trim(preg_replace('/\s{2,}/u', ' ', $out));
    $out = preg_replace('/\s+([\/\-])/', ' $1', $out);
    // capitalise first letter only if it is Latin
    if (preg_match('/^[a-z]/', $out)) {
        $out = ucfirst($out);
    }

    return $out;
}

