    '/(?<![\x{10A0}-\x{10FF}])ძრ\s+(\d)/u' => 'base $1',
    '/(?<![\x{10A0}-\x{10FF}])სექციით(?![\x{10A0}-\x{10FF}])/u' => 'sections',
